// Function to get flag emoji from country code
export function getFlagEmoji(countryCode) {
  const defaultFlag = '🏳️'; // fallback flag
  if (!countryCode || countryCode.length !== 2) return defaultFlag;

  try {
    const flag = countryCode.toUpperCase().replace(/./g, (char) => String.fromCodePoint(127397 + char.charCodeAt()));

    // Basic validity check: flag should be 4 bytes (2 regional indicators)
    return flag.length === 4 ? flag : defaultFlag;
  } catch {
    return defaultFlag;
  }
}

// Create flag map for all country codes
export const flagMap = Object.fromEntries(countryCodes.map((code) => [code, getFlagEmoji(code)]));

// Additional mappings for country slugs
export const additionalFlagMappings = {
  uae: '🇦🇪',
  uk: '🇬🇧',
  'united-kingdom': '🇬🇧',
  belgium: '🇧🇪'
};

// Combined flag map that includes both ISO codes and slugs
export const combinedFlagMap = {
  ...flagMap,
  ...additionalFlagMappings
};

// Main function to get flag for a country
export function getCountryFlag(countryCodeOrSlug) {
  if (!countryCodeOrSlug) return '🏁';

  // Try exact match first
  if (combinedFlagMap[countryCodeOrSlug]) {
    return combinedFlagMap[countryCodeOrSlug];
  }

  // Try case-insensitive match
  const upperCaseKey = countryCodeOrSlug.toUpperCase();
  if (combinedFlagMap[upperCaseKey]) {
    return combinedFlagMap[upperCaseKey];
  }

  // Fallback to generated emoji for 2-letter codes
  if (countryCodeOrSlug.length === 2) {
    return getFlagEmoji(countryCodeOrSlug);
  }

  return '🏁'; // Default flag
}
